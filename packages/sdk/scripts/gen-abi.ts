// Copies the CreditDesk and SessionGate ABIs out of the Foundry build into src/abi/*.ts.
// Run from the repo root after a build:
//   forge build --root contracts && pnpm --filter @boundline/sdk gen-abi
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, "../../..");
const outDirs = ["out", "out-lane-c", "out-lane-a", "out-lane-b", "out-lane-d"];

function artifactFor(contract: string): string {
  const found = outDirs.map((d) => resolve(repo, "contracts", d, `${contract}.sol`, `${contract}.json`)).find((p) => existsSync(p));
  if (!found) throw new Error(`no ${contract} artifact; run \`forge build --root contracts\` first`);
  return found;
}

function emit(contract: string, exportName: string, file: string): void {
  const artifact = artifactFor(contract);
  const json = JSON.parse(readFileSync(artifact, "utf8")) as { abi: unknown[] };
  const out = resolve(here, "../src/abi", file);
  const header = `// Generated by scripts/gen-abi.ts from ${artifact.replace(repo + "/", "")}. Do not edit by hand.\n`;
  writeFileSync(out, `${header}export const ${exportName} = ${JSON.stringify(json.abi, null, 2)} as const;\n`);
  console.log(`wrote ${out.replace(repo + "/", "")} (${json.abi.length} entries)`);
}

emit("CreditDesk", "creditDeskAbi", "creditDesk.ts");
emit("SessionGate", "sessionGateAbi", "sessionGate.ts");
