// Records one real aggregate3 response for the default read plan as the decoder test's fixture.
// Run: pnpm --filter @boundline/observatory exec tsx scripts/record-aggregate3.ts [rpc-url]
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { MULTICALL3 } from "../src/encoding.js";
import { DEFAULT_PLAN, rpcUrlsOf } from "../src/reader.js";
import { ethCaller } from "../src/rpc.js";

const rpc = process.argv[2] ?? process.env.BASE_RPC_URL ?? "https://base-rpc.publicnode.com";
const result = await ethCaller(rpcUrlsOf(rpc))(MULTICALL3, DEFAULT_PLAN.data);
const out = resolve(dirname(fileURLToPath(import.meta.url)), "../test/fixtures/aggregate3-mainnet.ts");
const recordedAt = new Date().toISOString();
const rpcHost = new URL(rpc).host;
const record = { recordedAt, rpcHost, tokens: DEFAULT_PLAN.tokens.map((t) => t.symbol), calls: DEFAULT_PLAN.calls.length, calldata: DEFAULT_PLAN.data, result };
writeFileSync(
  out,
  `// Generated by scripts/record-aggregate3.ts on ${recordedAt} from ${rpcHost}: one real aggregate3 response for the\n` +
    `// default read plan (${DEFAULT_PLAN.calls.length} calls). Re-record when the token list in @boundline/chain changes; do not edit.\n` +
    `export const AGGREGATE3_FIXTURE = ${JSON.stringify(record, null, 2)} as const;\n`,
);
console.log(`wrote ${out}: ${result.length / 2 - 1} bytes of return data for ${DEFAULT_PLAN.calls.length} calls`);
