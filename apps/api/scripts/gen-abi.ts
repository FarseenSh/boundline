// Copies the CreditDesk ABI out of the Foundry build into src/abi/creditDesk.ts.
// Run from the repo root after a build:
//   FOUNDRY_PROFILE=lane-b forge build --root contracts && pnpm --filter @boundline/api exec tsx scripts/gen-abi.ts
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, "../../..");
const candidates = ["out-lane-b", "out", "out-lane-a", "out-lane-c", "out-lane-d"].map((d) =>
  resolve(repo, "contracts", d, "CreditDesk.sol", "CreditDesk.json"),
);
const artifact = candidates.find((p) => existsSync(p));
if (!artifact) {
  console.error("no CreditDesk artifact; run `forge build --root contracts` first");
  process.exit(1);
}
const json = JSON.parse(readFileSync(artifact, "utf8")) as { abi: unknown[] };
const out = resolve(here, "../src/abi/creditDesk.ts");
const header = `// Generated by scripts/gen-abi.ts from ${artifact.replace(repo + "/", "")}. Do not edit by hand.\n`;
writeFileSync(out, `${header}export const creditDeskAbi = ${JSON.stringify(json.abi, null, 2)} as const;\n`);
console.log(`wrote ${out.replace(repo + "/", "")} (${json.abi.length} entries)`);
