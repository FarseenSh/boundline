import { describe, expect, it } from "vitest";
import { toEventSelector, type Abi, type AbiEvent } from "viem";
import { aaveSpokeAbi, b20AssetAbi } from "@boundline/chain";
import { answerUpdatedAbi, boundlineStackAbi, creditDeskAbi, mainnetOracleRegistryEventsAbi, morphoEventsAbi, policyRegistryEventsAbi, sepoliaProtectionAbi } from "../src/abis.js";
import { TOPIC0, eventSignature, topic0Of } from "../src/topics.js";

const ABIS: Abi[] = [morphoEventsAbi, boundlineStackAbi, creditDeskAbi, sepoliaProtectionAbi, answerUpdatedAbi, mainnetOracleRegistryEventsAbi, policyRegistryEventsAbi, b20AssetAbi, aaveSpokeAbi] as Abi[];

describe("precomputed topic0 table (src/topics.ts, generated by scripts/gen-topics.ts)", () => {
  it("holds every event of every ABI the indexer decodes, equal to viem's selector (re-run gen-topics when this fails)", () => {
    let n = 0;
    for (const abi of ABIS) {
      for (const item of abi) {
        if (item.type !== "event" || item.anonymous) continue;
        const sig = eventSignature(item as AbiEvent);
        expect({ sig, topic0: TOPIC0[sig] }).toEqual({ sig, topic0: toEventSelector(item as AbiEvent) });
        n += 1;
      }
    }
    expect(n).toBeGreaterThan(90);
  });
  it("writes tuple signatures canonically", () => {
    const create = (morphoEventsAbi as Abi).find((x) => x.type === "event" && x.name === "CreateMarket") as AbiEvent;
    expect(eventSignature(create)).toBe("CreateMarket(bytes32,(address,address,address,address,uint256))");
    expect(topic0Of(create)).toBe(toEventSelector(create));
  });
});
